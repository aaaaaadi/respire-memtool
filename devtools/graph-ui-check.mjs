async (page) => {
  const check=(ok,message)=>{if(!ok)throw Error(message)};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1000,height:760});
  await page.goto('http://127.0.0.1:1423/');
  await page.getByRole('button',{name:'图谱',exact:true}).click();
  await page.waitForFunction(()=>window.__graphView?.nodes?.length===5);
  await page.waitForFunction(()=>!document.querySelector('#graph-loading').classList.contains('hidden')===false);
  await page.evaluate(async()=>{await new Promise(resolve=>setTimeout(resolve,1500));});
  await page.evaluate(()=>window.__graphView.setContainerVisible(false));
  const position=id=>page.evaluate(id=>{
    const v=window.__graphView,n=v.nodeById.get(id),r=v.graph.renderer().domElement.getBoundingClientRect();
    const p=v.graph.graph2ScreenCoords(n.x,n.y,n.z);return {x:r.x+p.x,y:r.y+p.y};
  },id);
  let p=await position('xml-1');
  await page.mouse.move(p.x+10,p.y);
  check(await page.locator('.graph-node-tooltip').isVisible(),'expanded hover area has no tooltip');
  check((await page.locator('.graph-node-tooltip').innerText()).includes('XML 注释配色'),'tooltip shows wrong title');
  await page.mouse.click(p.x+10,p.y);
  check(await page.evaluate(()=>window.__graphView.pinnedId==='xml-1'),'nearby click missed small node');
  check((await page.locator('#graph-detail-title,.graph-detail-title').innerText()).includes('XML 注释配色'),'detail selection differs');
  const other=await position('ts-2');await page.mouse.move(other.x,other.y);
  await page.waitForFunction(()=>window.__graphView.hoverId==='ts-2');
  check(await page.evaluate(()=>window.__graphView._roots()[0]==='xml-1'),'hover replaced locked selection');
  await page.getByRole('button',{name:'自转',exact:true}).click();
  check(await page.evaluate(()=>window.__graphView.graph.controls().autoRotate),'rotation failed to start');
  const input=page.getByRole('searchbox',{name:'搜索图谱节点'});
  await input.fill('前端');
  await page.locator('#graph-search-results button').filter({hasText:'TypeScript 前端'}).click();
  check(await page.evaluate(()=>window.__graphView.pinnedId==='ts-2'&&!window.__graphView.graph.controls().autoRotate),'search did not select and pause rotation');
  await page.waitForFunction(()=>{const v=window.__graphView,n=v.nodeById.get('ts-2');return v.graph.controls().target.distanceTo({x:n.x,y:n.y,z:n.z})<1;});
  check(!await page.locator('#graph-rotate').evaluate(n=>n.classList.contains('active')),'rotation button is stale');
  await page.screenshot({path:'output/playwright/graph-selected.png'});
  await page.getByRole('button',{name:'取消选择',exact:true}).click();
  check(await page.evaluate(()=>window.__graphView.pinnedId===null),'clear selection did not clear pin');
  check(!await page.locator('#graph-detail').isVisible(),'clear selection kept details open');
  await input.fill('<img');
  check(await page.locator('#graph-search-results img').count()===0,'search result interpreted title as HTML');
  check(await page.locator('#graph-search-results button').count()===1,'literal title search failed');
  await page.screenshot({path:'output/playwright/graph-search.png'});
  await page.evaluate(()=>{window.__escapedToDocument=0;document.addEventListener('keydown',e=>{if(e.key==='Escape')window.__escapedToDocument++});});
  await input.fill('IDEA'); await input.press('Escape');
  check(await page.evaluate(()=>window.__escapedToDocument===0),'search Escape bubbled to global hide shortcut');
  check(!await page.evaluate(()=>window.__fixtureHidden),'search Escape hid the application');
  check(!await page.locator('#graph-search-results').isVisible(),'search Escape retained dropdown');
  await input.fill('IDEA'); await input.press('Escape');
  check(!await page.evaluate(()=>window.__fixtureHidden),'search Escape hid the application');
  check(!await page.locator('#graph-search-results').isVisible(),'search Escape retained dropdown');
  await input.fill('IDEA'); await input.press('ArrowDown');
  await page.locator('#graph-search-results button').first().press('Escape');
  check(!await page.locator('#graph-search-results').isVisible(),'candidate Escape reopened dropdown');
  check(await page.evaluate(()=>window.__escapedToDocument===0),'candidate Escape bubbled to hide shortcut');
  await input.fill('不存在');
  check((await page.locator('#graph-search-results').innerText()).includes('没有匹配'),'empty results missing');
  await input.fill('');
  await page.evaluate(()=>window.__graphView.zoomToFit());
  await page.evaluate(async()=>{await new Promise(resolve=>setTimeout(resolve,800));});
  p=await position('xml-1');
  await page.mouse.move(p.x,p.y);await page.mouse.down();await page.mouse.move(p.x+2,p.y+1);await page.mouse.up();
  check(await page.evaluate(()=>window.__graphView.pinnedId==='xml-1'),'minor pointer jitter discarded click');
  p=await position('xml-1');
  await page.mouse.move(p.x,p.y);await page.mouse.down();await page.mouse.move(p.x+90,p.y+40,{steps:8});await page.mouse.up();
  check(await page.evaluate(()=>window.__graphView.pinnedId==='xml-1'),'drag changed selection');
  await page.locator('.graph-detail-close').click();
  check(await page.evaluate(()=>window.__graphView.pinnedId===null),'close detail left stale pin');
  await input.fill('xml-1');await input.press('Enter');
  check(await page.evaluate(()=>window.__graphView.pinnedId==='xml-1'),'keyboard selection failed');
  await page.evaluate(()=>window.__graphView.applyOps([{op:'node.remove',id:'xml-1'}]));
  check(await page.evaluate(()=>window.__graphView.pinnedId===null),'removed node remained selected');
  check(!await page.locator('#graph-detail').isVisible(),'removed node retained stale detail');
  await page.setViewportSize({width:480,height:560});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=480),'narrow graph overflows horizontally');
  check(errors.length===0,'page errors: '+errors.join('; '));
  return {checks:['nearby-click','expanded-hover-tooltip','locked-highlight','search-camera-focus','selection-pauses-rotation','clear-and-close','literal-title-safe','empty-search','minor-jitter','drag-preserves-selection','keyboard-search','search-escape-isolated','deleted-node-clears-selection','narrow-window'],errors};
}
